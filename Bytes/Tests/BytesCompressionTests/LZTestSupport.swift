// Shared by the LZ4, LZVN, and LZFSE tests: reference encodings (Apple's Compression, and the lzfse reference's
// LZFSE and LZVN streams), sample inputs, and a driver that decodes between exactly sized allocations, so that
// any access past either buffer is a heap overflow (run with `--sanitize=address` to catch one).

/// Compression's encoding of `data` with `algorithm`, through its buffer API.
func appleEncode(_ data: [UInt8], _ algorithm: compression_algorithm) -> [UInt8] {
    AppleCompression.encode(data, algorithm)
}

/// Compression's decoding of `data` into at most `capacity` bytes.
func appleDecode(_ data: [UInt8], capacity: Int, _ algorithm: compression_algorithm) -> [UInt8] {
    AppleCompression.decode(data, capacity: capacity, algorithm)
}

/// Compression's encoding of `data` with `algorithm` into `capacity` bytes, or `nil` where it fails (returns 0).
func appleEncode(_ data: [UInt8], _ algorithm: compression_algorithm, capacity: Int) -> [UInt8]? {
    AppleCompression.encode(data, algorithm, capacity: capacity)
}

/// Compression's raw LZVN (`compression_encode_buffer`'s undocumented algorithm 0x900: APFS `decmpfs` type 8).
let COMPRESSION_LZVN_RAW = AppleCompression.lzvnRaw

/// The lzfse reference encoder's LZFSE stream for `data`, written by Bytes' encoder with the reference's parse (its
/// bytes, checked by digest in LZFSEEncoderTests: the reference itself isn't built).
func lzfseReferenceEncode(_ data: [UInt8]) throws(BytesError) -> [UInt8] {
    var encoder = LZFSEEncoder(parse: .reference)
    var output = [UInt8](repeating: 0, count: LZFSEEncoder.maximumCompressedSize(forByteCount: data.count))
    let size = try output.withOutputRawSpan { span throws(BytesError) in
        try encoder.compressAll(data.span.bytes, into: &span)
    }
    return Array(output[..<size])
}

/// The lzfse reference encoder's raw LZVN stream for `data` (ending with the end-of-stream opcode), written by
/// Bytes' encoder, as ``lzfseReferenceEncode(_:)``.
func lzvnReferenceEncode(_ data: [UInt8]) throws(BytesError) -> [UInt8] {
    var encoder = LZVNEncoder(parse: .reference)
    var output = [UInt8](repeating: 0, count: LZVNEncoder.maximumCompressedSize(forByteCount: data.count))
    let size = try output.withOutputRawSpan { span throws(BytesError) in
        try encoder.compressAll(data.span.bytes, into: &span)
    }
    return Array(output[..<size])
}

/// SHA-256 of byte strings, each preceded by its length (little-endian, 64-bit), in hex: how tests check against
/// results recorded from references that are no longer built.
func goldenDigest(_ streams: [[UInt8]]) -> String {
    var hash = SHA256()
    for stream in streams {
        withUnsafeBytes(of: UInt64(stream.count).littleEndian) { hash.update(bufferPointer: $0) }
        hash.update(data: stream)
    }
    return hash.finalize().map { String(format: "%02x", $0) }.joined()
}

/// Runs `body` with a span over an exact copy of `input` and an output span over exactly `capacity` fresh bytes.
///
/// - Returns: What `body` returned or threw, and the bytes it appended.
func withExactBuffers<R>(
    _ input: [UInt8], capacity: Int, _ body: (RawSpan, inout OutputRawSpan) throws(BytesError) -> R
) -> (result: Result<R, BytesError>, output: [UInt8]) {
    let inputBytes = UnsafeMutableRawBufferPointer.allocate(byteCount: input.count, alignment: 1)
    defer { inputBytes.deallocate() }
    input.withUnsafeBytes { inputBytes.copyMemory(from: $0) }
    let outputBytes = UnsafeMutableRawBufferPointer.allocate(byteCount: capacity, alignment: 1)
    defer { outputBytes.deallocate() }
    let span = RawSpan(_unsafeBytes: UnsafeRawBufferPointer(inputBytes))
    var output = OutputRawSpan(buffer: outputBytes, initializedCount: 0)
    let result: Result<R, BytesError>
    do throws(BytesError) {
        result = .success(try body(span, &output))
    } catch {
        result = .failure(error)
    }
    let written = output.finalize(for: outputBytes)
    return (result, Array(UnsafeRawBufferPointer(rebasing: outputBytes[..<written])))
}

/// Sample inputs: text, incompressible bytes, runs, short periods (matches at distances 1 to 16), and mixes of
/// them, at sizes around the formats' block and copy boundaries (generated by BytesTestSupport's `SampleBytes`).
enum LZSamples {
    static let sizes = [
        0, 1, 2, 3, 4, 5, 7, 8, 9, 12, 13, 15, 16, 17, 31, 32, 33, 47, 48, 63, 64, 65, 100, 127, 128, 255, 256, 257,
        1000, 1023, 4095, 4096, 4097, 10_000, 40_000, 65_535, 65_536, 65_537, 100_003, 262_147,
    ]

    /// English-like words: compressible, with matches of every length and distance.
    static func text(_ count: Int, seed: UInt64) -> [UInt8] { SampleBytes.text(count, seed: seed) }

    static func random(_ count: Int, seed: UInt64) -> [UInt8] { SampleBytes.random(count, seed: seed) }

    /// A random pattern of `period` bytes, repeated.
    static func periodic(_ count: Int, period: Int, seed: UInt64) -> [UInt8] {
        SampleBytes.periodic(count, period: period, seed: seed)
    }

    /// Text, random bytes, runs, and periodic stretches, in pieces of random sizes.
    static func mixed(_ count: Int, seed: UInt64) -> [UInt8] { SampleBytes.mixed(count, seed: seed) }

    /// Every kind at every size, plus periods 1 through 16 at a few sizes.
    static let all: [(name: String, bytes: [UInt8])] = {
        var samples: [(String, [UInt8])] = []
        for size in sizes {
            samples.append(("text \(size)", text(size, seed: UInt64(size))))
            samples.append(("random \(size)", random(size, seed: UInt64(size))))
            samples.append(("run \(size)", [UInt8](repeating: 0x61, count: size)))
            samples.append(("mixed \(size)", mixed(size, seed: UInt64(size))))
        }
        for period in 1...16 {
            for size in [40, 300, 5000, 70_000] {
                samples.append(("period \(period) \(size)", periodic(size, period: period, seed: UInt64(period))))
            }
        }
        return samples
    }()

    /// Larger inputs: several of each format's blocks, up to the 16 MiB an archive segment holds.
    static let large: [(name: String, bytes: [UInt8])] = [
        ("text 1 MiB + 7", text((1 << 20) + 7, seed: 1)),
        ("mixed 3 MiB + 1", mixed((3 << 20) + 1, seed: 2)),
        ("random 1 MiB", random(1 << 20, seed: 3)),
        ("text 16 MiB", text(16 << 20, seed: 4)),
    ]
}
