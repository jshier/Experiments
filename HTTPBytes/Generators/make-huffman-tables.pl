#!/usr/bin/perl
# Generates the HPACK/QPACK Huffman code's tables (RFC 7541 Appendix B; QPACK uses the same code, RFC 9204 §4.1.2) as
# Swift literal arrays:
#
#   Sources/HTTPBytes/Huffman/HuffmanTables.swift
#
# Run from anywhere: Generators/make-huffman-tables.pl. Input: hpack-huffman.tsv, one row per symbol: symbol (0-256),
# code in hex, length in bits. Every table is a literal `let` array of integer literals, so Swift initializes it
# statically (no swift_once). The design (a 14-bit multi-symbol decode table, canonical decoding for longer codes, codes
# left-aligned with their lengths for the encoder) was chosen by prototypes measured against ls-hpack (HTTPBytes'
# RESULTS.md, "HPACK").
use strict;
use warnings;
use File::Basename qw(dirname);
use File::Path qw(make_path);

my $here = dirname(__FILE__);
my $outDir = "$here/../Sources/HTTPBytes/Huffman";
make_path($outDir);
my $K = 14;                     # decode table bits

open(my $fh, '<', "$here/hpack-huffman.tsv") or die "hpack-huffman.tsv: $!\n";
my (@code, @len);
while (<$fh>) {
    chomp;
    next unless /\S/;
    my ($sym, $hex, $bits) = split /\t/;
    $code[$sym] = hex($hex);
    $len[$sym] = $bits;
}
close $fh;
die "expected 257 symbols\n" unless @code == 257;

# Checks: canonical (codes of one length consecutive by symbol; lengths' first codes as in a canonical code), complete
# (Kraft sum exactly 1), EOS all ones.
my %byLen;
push @{ $byLen{$len[$_]} }, $_ for 0 .. 256;
my @lengths = sort { $a <=> $b } keys %byLen;
{
    my $next = 0;
    my $prevLen = 0;
    for my $l (@lengths) {
        $next <<= ($l - $prevLen);
        for my $s (@{ $byLen{$l} }) {
            die "not canonical at symbol $s\n" unless $code[$s] == $next;
            $next++;
        }
        $prevLen = $l;
    }
    die "code not complete\n" unless $next == (1 << $prevLen);
    die "EOS not all ones\n" unless $code[256] == (1 << 30) - 1 && $len[256] == 30;
}

sub bitstr { my ($s) = @_; return sprintf("%0*b", $len[$s], $code[$s]); }

# The symbol whose code is a prefix of a bit string (the code is complete, so there is one when it's 30 bits or more).
my %symOf;
$symOf{ bitstr($_) } = $_ for 0 .. 256;
sub firstSymbol {
    my ($bits) = @_;
    for my $l (5 .. 30) {
        last if $l > length $bits;
        my $s = $symOf{ substr($bits, 0, $l) };
        return ($s, $l) if defined $s;
    }
    return (undef, undef);
}

my $out = '';
sub emitArray {
    my ($name, $type, $doc, $perLine, $fmt, @values) = @_;
    $out .= $doc;
    $out .= "\@usableFromInline let $name: [$type] = [\n";
    for (my $i = 0; $i < @values; $i += $perLine) {
        my $end = $i + $perLine - 1;
        $end = $#values if $end > $#values;
        $out .= "    " . join(", ", map { sprintf($fmt, $_) } @values[$i .. $end]) . ",\n";
    }
    $out .= "]\n\n";
}

$out .= "// Generated by Generators/make-huffman-tables.pl from hpack-huffman.tsv (RFC 7541 Appendix B). Don't edit.\n";
$out .= "// Every table is a literal array of integer literals: statically initialized, no swift_once.\n\n";

# Encoder: code and length in one word, the code in bits 32-63 left-aligned to bit 63, the length in bits 0-7.
emitArray('hpackHuffmanEncodeTable', 'UInt64',
    "/// Each byte's code left-aligned in the high 32 bits (`code << (32 - length) << 32`), its length in bits 0-7;\n"
    . "/// entry 256 is 0 (no bits), for padding a batch.\n",
    4, '0x%016x', (map { (($code[$_] << (32 - $len[$_])) << 32) | $len[$_] } 0 .. 255), 0);

# Multi-symbol decoding, indexed by the next K bits. Entry: bits 0-4: bits consumed; bit 5: 0 (so a shift by the whole
# entry shifts by the count); bits 6-7: symbols decoded (0: the first code is longer than K bits); bits 8-15, 16-23:
# the symbols; bit 24: one of them is NUL, LF, or CR.
{
    my $max = 2;
    my @t;
    for my $w (0 .. (1 << $K) - 1) {
        my $bits = sprintf("%0*b", $K, $w);
        my ($used, @syms) = (0);
        while (@syms < $max) {
            my ($s, $l) = firstSymbol(substr($bits, $used));
            last unless defined $s;
            die "EOS within $K bits\n" if $s == 256;
            push @syms, $s;
            $used += $l;
        }
        my $e = $used | (scalar(@syms) << 6);
        $e |= $syms[$_] << (8 + 8 * $_) for 0 .. $#syms;
        # Bit 24: a symbol HTTP/2 field values can't have (NUL, LF, CR: RFC 9113 §8.2.1), ORed up by the decoder so it
        # can report them without scanning its output.
        $e |= 1 << 24 if grep { $_ == 0 || $_ == 10 || $_ == 13 } @syms;
        push @t, $e;
    }
    emitArray('hpackHuffmanDecodeTable', 'UInt32',
        "/// Multi-symbol decoding, $K bits at a time (" . (1 << $K) . " entries, up to $max symbols each).\n"
        . "/// Bits 0-4: bits consumed; bit 5: 0; bits 6-7: symbols decoded (0: the first code is longer than $K bits);\n"
        . "/// bits 8-15, 16-23: the symbols; bit 24: one of them is NUL, LF, or CR.\n", 8, '0x%08x', @t);
}

# Canonical decoding, for codes longer than the table's K bits. With a 32-bit window `w` (the next bits, left-aligned
# in the low 32 bits of a UInt64, ones past the end), the code's length is the least L with w < limit[L], and the
# symbol is symbols[(w >> (32 - L)) + offset[L]].
{
    my @sorted;
    my (@limit, @offset);
    my ($first, $prevLen, $index) = (0, 0, 0);
    @limit = (0) x 32;
    @offset = (0) x 32;
    for my $l (@lengths) {
        $first <<= ($l - $prevLen);
        my $count = scalar @{ $byLen{$l} };
        $offset[$l] = $index - $first;
        push @sorted, @{ $byLen{$l} };
        $index += $count;
        $first += $count;
        $limit[$l] = $first << (32 - $l);
        $prevLen = $l;
    }
    # Lengths no code has: their limit is the previous length's, so the search passes over them.
    for my $l (1 .. 31) { $limit[$l] = $limit[$l - 1] if !exists $byLen{$l}; }
    $limit[31] = 1 << 32;
    emitArray('hpackHuffmanCanonicalLimit', 'UInt64',
        "/// For each length L, one past the last left-aligned 32-bit window whose code is at most L bits.\n",
        4, '0x%09x', @limit);
    emitArray('hpackHuffmanCanonicalOffset', 'Int32',
        "/// For each length L, the index of its first symbol in `hpackHuffmanCanonicalSymbols` less its first code.\n",
        8, '%d', @offset);
    # The shortest code with exactly c leading ones (c = 0...32): where the canonical search can start.
    my @start;
    for my $c (0 .. 32) {
        my $min = 31;
        for my $s (0 .. 256) {
            my $b = bitstr($s);
            my $lead = ($b =~ /^(1*)/) ? length($1) : 0;
            $min = $len[$s] if $lead == $c && $len[$s] < $min;
        }
        $min = $start[$c - 1] if $min == 31 && $c > 0;
        push @start, $min;
    }
    emitArray('hpackHuffmanLengthByLeadingOnes', 'UInt8',
        "/// For c leading ones, the shortest code that has exactly c (or, if none, the entry before's).\n", 16, '%d', @start);
    emitArray('hpackHuffmanCanonicalSymbols', 'UInt16',
        "/// Symbols in canonical order: by code length, then symbol.\n", 16, '%d', @sorted);
}

$out =~ s/\n\n\z/\n/;
open(my $outFile, '>', "$outDir/HuffmanTables.swift") or die $!;
print $outFile $out;
close $outFile;
