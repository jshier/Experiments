// HPACK's Huffman code (RFC 7541 §5.2, Appendix B), which QPACK uses too (RFC 9204 §4.1.2).
//
// Decoding: a 14-bit multi-symbol table (16,384 UInt32 entries, 64 KB; up to 2 symbols an entry), the input read as if
// it continued with ones forever, so the loop has no end-of-input test: EOS's 30 ones end every string. Codes longer
// than 14 bits are decoded canonically, out of line.
// Encoding: 8 codes merged off the writer's dependency chain when they fit 56 bits (else 4 and 4), then one shift, OR,
// and 8-byte store per merge; string literals encoded optimistically after a one-byte length prefix, and written raw
// if the code isn't shorter.
//
// Chosen by prototypes measured against ls-hpack (RESULTS.md, "HPACK"). Tables: HuffmanTables.swift, generated by
// Generators/make-huffman-tables.pl.

/// Why a Huffman-coded string was rejected, or couldn't be written.
@frozen
public enum HPACKHuffmanError: Error, Equatable, Sendable {
    /// EOS in the string, padding longer than 7 bits, or padding that isn't all ones (RFC 7541 §5.2).
    case invalidEncoding
    /// The output has no room for the result.
    case outputTooSmall
}

/// HPACK's and QPACK's Huffman code: decoding and encoding string literals' bytes.
///
/// ```swift
/// try HPACKHuffman.decode(coded, into: &output)        // appends the decoded bytes
/// try HPACKHuffman.encodeStringLiteral(value, into: &output)   // H flag, length, then code or bytes
/// ```
///
/// The HPACK and QPACK coders call the pointer forms (`huffmanDecode(input:inputCount:output:capacity:)` and others),
/// converting their buffers once per field block rather than per string.
public enum HPACKHuffman {
    /// Decodes a Huffman-coded string literal's bytes, appending them to `output`.
    ///
    /// The fast loop needs 13 bytes of room past what it writes; with less, the last bytes decode carefully.
    @inlinable
    public static func decode(_ input: RawSpan, into output: inout OutputRawSpan) throws(HPACKHuffmanError) {
        let result = input.withUnsafeBytes { source in
            // Unsafe: the closure gets the span's whole memory; the decoder writes only past `initialized`, below the
            // capacity it's given, and reports the bytes it initialized.
            unsafe output.withUnsafeMutableBytes { target, initialized in
                let written = unsafe withFreeBytes(target, from: initialized) { base, capacity in
                    unsafe huffmanDecode(input: source.baseAddress, inputCount: source.count, output: base, capacity: capacity)
                }
                guard written >= 0 else { return written }
                let count = written & (huffmanForbiddenCharacters &- 1)
                initialized &+= count
                return count
            }
        }
        switch result {
        case huffmanInvalid: throw .invalidEncoding
        case huffmanOutputFull: throw .outputTooSmall
        default: return
        }
    }

    /// The length of `input` Huffman-coded, in bytes.
    @inlinable
    public static func encodedCount(of input: RawSpan) -> Int {
        input.withUnsafeBytes { bytes in
            // Unsafe: the span's own bytes, read within its count.
            unsafe huffmanEncodedCount(bytes.baseAddress?.assumingMemoryBound(to: UInt8.self), bytes.count)
        }
    }

    /// Huffman-codes `input`, appending to `output`.
    @inlinable
    public static func encode(_ input: RawSpan, into output: inout OutputRawSpan) throws(HPACKHuffmanError) {
        let written = input.withUnsafeBytes { source in
            // Unsafe: the closure gets the span's whole memory; the encoder writes only past `initialized`, below the
            // capacity it's given, and reports the bytes it initialized.
            unsafe output.withUnsafeMutableBytes { target, initialized in
                let n = unsafe withFreeBytes(target, from: initialized) { base, capacity in
                    unsafe huffmanEncode(source.baseAddress?.assumingMemoryBound(to: UInt8.self), source.count, base, capacity)
                }
                if n >= 0 { initialized &+= n }
                return n
            }
        }
        if written < 0 { throw .outputTooSmall }
    }

    /// Writes a string literal (RFC 7541 §5.2): the H flag and 7-bit prefix length, then the Huffman code if it's
    /// shorter than the bytes, else the bytes.
    ///
    /// Encodes optimistically after a one-byte prefix and gives up once the code is as long as the bytes; a code of
    /// 127 bytes or more moves up to make room for the longer prefix.
    @inlinable
    public static func encodeStringLiteral(_ input: RawSpan, into output: inout OutputRawSpan) throws(HPACKHuffmanError) {
        let written = input.withUnsafeBytes { source in
            // Unsafe: as in `encode(_:into:)`.
            unsafe output.withUnsafeMutableBytes { target, initialized in
                let n = unsafe withFreeBytes(target, from: initialized) { base, capacity in
                    unsafe huffmanStringLiteral(source.baseAddress?.assumingMemoryBound(to: UInt8.self), source.count, base, capacity)
                }
                if n >= 0 { initialized &+= n }
                return n
            }
        }
        if written < 0 { throw .outputTooSmall }
    }
}

/// The free part of an output span's memory, as a pointer and capacity (a placeholder when there's none: the coders
/// then write nothing).
@inlinable @inline(__always)
package func withFreeBytes(
    _ target: UnsafeMutableRawBufferPointer, from initialized: Int,
    _ body: (UnsafeMutablePointer<UInt8>, Int) -> Int
) -> Int {
    // Unsafe: bytes [initialized, count) of the span's memory, uninitialized; the coders write only below `capacity`.
    // With no memory at all (a nil base), a dangling pointer and capacity 0: never written through. (A pointer to a local
    // placeholder instead cost a stack protector check per call.)
    guard let base = target.baseAddress else { return unsafe body(UnsafeMutablePointer(bitPattern: 1)!, 0) }
    return unsafe body(base.assumingMemoryBound(to: UInt8.self) + initialized, target.count &- initialized)
}

// MARK: - Decoding

/// The decoders' result for an invalid string (RFC 7541 §5.2).
@inlinable package var huffmanInvalid: Int { -1 }
/// The decoders' result when the output is full.
@inlinable package var huffmanOutputFull: Int { -2 }
let decodeEnd = -3

/// Added to the decoders' result when the output has NUL, LF, or CR.
@inlinable package var huffmanForbiddenCharacters: Int { 1 << 40 }

/// The table entries' bit 24, ORed, as `huffmanForbiddenCharacters`.
@inline(__always)
func forbiddenFlag(_ seen: UInt32) -> Int { Int(truncatingIfNeeded: seen & 1 << 24) &<< 16 }

/// Bit 24 for NUL, LF, and CR, decoded by the canonical code.
@inline(__always)
func forbiddenBit(_ symbol: Int) -> UInt32 { symbol == 0 || symbol == 10 || symbol == 13 ? 1 << 24 : 0 }

/// Bits 0-4 of a table entry: bits consumed; bit 5: 0; bits 6-7: symbols (0: the first code is longer than 14 bits);
/// bits 8-23: up to 2 symbols.
let decodeTableBits: UInt64 = 14
let decodeBatch = 4                 // 4 × 14 <= 56 bits per refill

/// The bit buffer: valid bits at the top of `bits`; their number in the low 6 bits of `count` (the fast loop subtracts
/// whole table entries, leaving the bits above meaningless); `next`, the next input byte (past the end once the virtual
/// ones are being read).
struct BitState {
    var bits: UInt64
    var count: UInt64
    var next: Int
}

/// The next 8 bytes from `next` when fewer than 8 remain: the real bytes, then ones.
@inline(__always)
func endWord(_ input: UnsafeRawPointer?, _ inputCount: Int, _ next: Int) -> UInt64 {
    let remaining = inputCount &- next
    guard remaining > 0, let input = unsafe input else { return ~0 }
    let ones = ~0 &>> UInt64(truncatingIfNeeded: remaining &<< 3)    // remaining is 1 through 7
    if inputCount >= 8 {
        // Unsafe: an unchecked load. Safe: inputCount >= 8. The last 8 bytes, moved up past those before `next`.
        let last = UInt64(bigEndian: unsafe input.loadUnaligned(fromByteOffset: inputCount &- 8, as: UInt64.self))
        return last &<< UInt64(truncatingIfNeeded: (8 &- remaining) &<< 3) | ones
    }
    // Fewer than 8 bytes in all, so `next` is 0: overlapping 4-byte loads, or the first, middle, and last bytes.
    let base = unsafe input + next
    if remaining >= 4 {
        // Unsafe: unchecked loads. Safe: bytes [0, 4) and [remaining - 4, remaining) are inside the input.
        let high = UInt64(UInt32(bigEndian: unsafe base.loadUnaligned(as: UInt32.self)))
        let low = UInt64(UInt32(bigEndian: unsafe base.loadUnaligned(fromByteOffset: remaining &- 4, as: UInt32.self)))
        return high &<< 32 | (low &<< UInt64(truncatingIfNeeded: (8 &- remaining) &<< 3)) & 0xFFFF_FFFF | ones
    }
    // Unsafe: unchecked loads. Safe: 1 <= remaining <= 3, and every offset is below it.
    let first = UInt64(unsafe base.load(as: UInt8.self))
    let middleOffset = remaining &>> 1
    let middle = UInt64(unsafe base.load(fromByteOffset: middleOffset, as: UInt8.self))
    let last = UInt64(unsafe base.load(fromByteOffset: remaining &- 1, as: UInt8.self))
    return first &<< 56 | middle &<< UInt64(truncatingIfNeeded: 56 &- (middleOffset &<< 3))
        | last &<< UInt64(truncatingIfNeeded: 56 &- ((remaining &- 1) &<< 3)) | ones
}

/// Fills the buffer to at least 56 bits: 8 real bytes, or the last ones and then ones.
@inline(__always)
func refill(_ state: inout BitState, _ input: UnsafeRawPointer?, _ inputCount: Int) {
    let word = state.next &+ 8 <= inputCount
        // Unsafe: an unchecked load. Safe: next + 8 <= inputCount (so the input isn't empty).
        ? UInt64(bigEndian: unsafe input.unsafelyUnwrapped.loadUnaligned(fromByteOffset: state.next, as: UInt64.self))
        : unsafe endWord(input, inputCount, state.next)
    state.bits |= word &>> state.count
    // Whole bytes that fit: the count becomes 56 + (count % 8), which is count | 56.
    state.next &+= Int(truncatingIfNeeded: (~state.count & 63) &>> 3)
    state.count |= 56
}

/// One symbol by the canonical code, from a 32-bit window (the next bits, in the low 32 bits).
@inline(__always)
func canonicalSymbol(_ window: UInt64) -> (symbol: Int, length: Int) {
    // Codes with more leading ones are longer: start at the shortest with as many.
    let leadingOnes = (~UInt32(truncatingIfNeeded: window)).leadingZeroBitCount
    var length = Int(hpackHuffmanLengthByLeadingOnes[leadingOnes])
    // Terminates: the limit for length 31 is 2^32, above any window.
    while window >= hpackHuffmanCanonicalLimit[length] { length &+= 1 }
    let index = Int(truncatingIfNeeded: window &>> UInt64(32 &- length)) &+ Int(hpackHuffmanCanonicalOffset[length])
    return (Int(hpackHuffmanCanonicalSymbols[index]), length)
}

/// A code longer than 14 bits, or the end when its 30 ones weren't all loaded yet. Out of line, values in and out, so
/// the fast loop's state stays in registers.
/// - Returns: The symbol (consumed from the state), `decodeEnd` at a valid end, or `huffmanInvalid`.
@inline(never)
func decodeLong(_ state: BitState, input: UnsafeRawPointer?, inputCount: Int) -> (symbol: Int, state: BitState) {
    var state = state
    if state.count < 30 { unsafe refill(&state, input, inputCount) }
    let position = state.next &<< 3 &- Int(truncatingIfNeeded: state.count)
    let dataBits = inputCount &<< 3
    // A symbol that ran into the virtual ones: its real bits weren't all ones, so not EOS's padding.
    if position > dataBits { return (huffmanInvalid, state) }
    if state.bits >= 0xFFFF_FFFC_0000_0000 { return (dataBits &- position <= 7 ? decodeEnd : huffmanInvalid, state) }
    let (symbol, length) = canonicalSymbol(state.bits &>> 32)
    if position &+ length > dataBits { return (huffmanInvalid, state) }
    state.bits &<<= UInt64(truncatingIfNeeded: length)
    state.count &-= UInt64(truncatingIfNeeded: length)
    return (symbol, state)
}

/// The output can't take the fast loop's 4-byte stores: a symbol at a time from the same state.
@inline(never)
func decodeCarefully(
    _ state: BitState, table: UnsafePointer<UInt32>, input: UnsafeRawPointer?, inputCount: Int,
    output: UnsafeMutablePointer<UInt8>, written: Int, capacity: Int, seen: UInt32
) -> Int {
    var state = state
    var out = written
    var seen = seen
    while true {
        if state.count < 30 { unsafe refill(&state, input, inputCount) }
        // Unsafe: an unchecked table read. Safe: a 14-bit index into 2^14 entries.
        let entry = unsafe table[Int(truncatingIfNeeded: state.bits &>> (64 &- decodeTableBits))]
        let symbol: Int
        let length: Int
        if entry & 0xC0 != 0 {
            symbol = Int(truncatingIfNeeded: (entry &>> 8) & 0xFF)
            seen |= entry
            length = Int(truncatingIfNeeded: hpackHuffmanEncodeTable[symbol] & 0xFF)
        } else {
            let (long, longState) = unsafe decodeLong(state, input: input, inputCount: inputCount)
            if long == decodeEnd { return out | forbiddenFlag(seen) }
            if long < 0 { return huffmanInvalid }
            guard out < capacity else { return huffmanOutputFull }
            seen |= forbiddenBit(long)
            // Unsafe: an unchecked store. Safe: out < capacity.
            unsafe output[out] = UInt8(truncatingIfNeeded: long)
            out &+= 1
            state = longState
            continue
        }
        let position = state.next &<< 3 &- Int(truncatingIfNeeded: state.count)
        if position &+ length > inputCount &<< 3 { return huffmanInvalid }   // into the virtual ones
        guard out < capacity else { return huffmanOutputFull }
        // Unsafe: an unchecked store. Safe: out < capacity.
        unsafe output[out] = UInt8(truncatingIfNeeded: symbol)
        out &+= 1
        state.bits &<<= UInt64(truncatingIfNeeded: length)
        state.count &-= UInt64(truncatingIfNeeded: length)
    }
}

/// The decoder. `@usableFromInline` and never inlined, so the table's address arrives as an opaque parameter: with the
/// global's address visible, LLVM folded the array header's offset into every lookup, an `add` on the lookup chain (and
/// an internal function with one caller gets the constant propagated in).
/// - Returns: Bytes written, or `huffmanInvalid` or `huffmanOutputFull`.
@usableFromInline @inline(never)
func huffmanDecodeLoop(
    table: UnsafePointer<UInt32>, input: UnsafeRawPointer?, inputCount: Int,
    output: UnsafeMutablePointer<UInt8>, capacity: Int
) -> Int {
    var bits: UInt64 = 0
    var count: UInt64 = 0
    var next = 0
    var out = 0
    var seen: UInt32 = 0                            // entries ORed: bit 24 for NUL, LF, CR
    let room = 3 &* decodeBatch &+ 1                // each lookup stores 4 bytes
    outer: while true {
        guard out &+ room <= capacity else {
            return unsafe decodeCarefully(
                BitState(bits: bits, count: count & 63, next: next), table: table, input: input,
                inputCount: inputCount, output: output, written: out, capacity: capacity, seen: seen)
        }
        let word = next &+ 8 <= inputCount
            // Unsafe: an unchecked load. Safe: next + 8 <= inputCount.
            ? UInt64(bigEndian: unsafe input.unsafelyUnwrapped.loadUnaligned(fromByteOffset: next, as: UInt64.self))
            : unsafe endWord(input, inputCount, next)
        bits |= word &>> count
        next &+= Int(truncatingIfNeeded: (~count & 63) &>> 3)
        count |= 56
        for _ in 0..<decodeBatch {
            // Unsafe: an unchecked table read. Safe: a 14-bit index into 2^14 entries.
            let entry = unsafe table[Int(truncatingIfNeeded: bits &>> (64 &- decodeTableBits))]
            if entry & 0xC0 == 0 {
                // The end: 30 ones at the top are EOS's bits, real or virtual (bits not yet loaded are zeros, so 30 ones
                // are all loaded). Valid if they start at most 7 bits before the end of the data.
                if bits >= 0xFFFF_FFFC_0000_0000 {
                    let position = next &<< 3 &- Int(truncatingIfNeeded: count & 63)
                    return UInt(bitPattern: inputCount &<< 3 &- position) <= 7 ? out | forbiddenFlag(seen) : huffmanInvalid
                }
                let (symbol, state) = unsafe decodeLong(
                    BitState(bits: bits, count: count & 63, next: next), input: input, inputCount: inputCount)
                if symbol < 0 { return symbol == decodeEnd ? out | forbiddenFlag(seen) : huffmanInvalid }
                seen |= forbiddenBit(symbol)
                (bits, count, next) = (state.bits, state.count, state.next)
                // Unsafe: an unchecked store. Safe: the room check left 4 bytes per lookup.
                unsafe output[out] = UInt8(truncatingIfNeeded: symbol)
                out &+= 1
                continue outer
            }
            // Unsafe: an unchecked 4-byte store. Safe: the room check left 4 bytes per lookup.
            unsafe UnsafeMutableRawPointer(output + out).storeBytes(of: entry &>> 8, as: UInt32.self)
            out &+= Int(truncatingIfNeeded: (entry &>> 6) & 3)
            seen |= entry
            // Bits 0-4 are the length and bit 5 is 0: a shift by the whole entry (mod 64) shifts by the length, and
            // subtracting it keeps the count's low 6 bits right.
            bits &<<= UInt64(entry)
            count &-= UInt64(entry)
        }
    }
}

/// Decodes `inputCount` Huffman-coded bytes into `output`, which has room for `capacity` bytes. Out of line: it gets
/// the table's address and calls the decoder (see `huffmanDecodeLoop`).
///
/// With 13 bytes of room past the decoded string, it's all decoded by the fast loop.
/// - Returns: Bytes written, with `huffmanForbiddenCharacters` added if they include NUL, LF, or CR (which HTTP/2 field
///   values can't: RFC 9113 §8.2.1, found from the table's entries, ORed, rather than a scan); or `huffmanInvalid` or
///   `huffmanOutputFull`.
@usableFromInline @inline(never)
package func huffmanDecode(
    input: UnsafeRawPointer?, inputCount: Int, output: UnsafeMutablePointer<UInt8>, capacity: Int
) -> Int {
    hpackHuffmanDecodeTable.withUnsafeBufferPointer { table in
        // Unsafe: the table's address, used during this call, while the global array lives.
        unsafe huffmanDecodeLoop(table: table.baseAddress!, input: input, inputCount: inputCount, output: output, capacity: capacity)
    }
}

// MARK: - Encoding

/// A most-significant-bit-first writer: bits fill a 64-bit word from bit 63 down and are stored 8 bytes at a time
/// (big-endian). Codes arrive left-aligned and are shifted right by the bits pending, so adding doesn't wait for the
/// new code's length.
@safe
struct MSBWriter {
    var bits: UInt64 = 0
    var pending: UInt64 = 0         // at most 7 after a flush
    var out: Int
    let base: UnsafeMutablePointer<UInt8>
    let capacity: Int

    @inline(__always)
    init(_ base: UnsafeMutablePointer<UInt8>, capacity: Int, at offset: Int) {
        unsafe self.base = base
        self.capacity = capacity
        out = offset
    }

    /// At most 56 bits between flushes.
    @inline(__always)
    mutating func add(leftAligned code: UInt64, length: UInt64) {
        bits |= code &>> pending
        pending &+= length
    }

    /// Stores the whole bytes; false if the output is full.
    @inline(__always)
    mutating func flush() -> Bool {
        if _fastPath(out &+ 8 <= capacity) {
            // Unsafe: an unchecked 8-byte store. Safe: out + 8 <= capacity.
            unsafe UnsafeMutableRawPointer(base + out).storeBytes(of: bits.bigEndian, as: UInt64.self)
            out &+= Int(truncatingIfNeeded: pending &>> 3)
            bits &<<= pending & 56
            pending &= 7
            return true
        }
        let ok: Bool
        (bits, pending, out, ok) = unsafe Self.flushCarefully(bits, pending, out, base, capacity)
        return ok
    }

    /// Static, values in and out: an out-of-line `mutating` call keeps the writer in memory in the caller's loop (it
    /// cost the per-symbol encoder 3.5x).
    @inline(never)
    static func flushCarefully(
        _ bits: UInt64, _ pending: UInt64, _ out: Int, _ base: UnsafeMutablePointer<UInt8>, _ capacity: Int
    ) -> (UInt64, UInt64, Int, Bool) {
        var (bits, pending, out) = (bits, pending, out)
        while pending >= 8 {
            guard out < capacity else { return (bits, pending, out, false) }
            // Unsafe: an unchecked store. Safe: out < capacity.
            unsafe base[out] = UInt8(truncatingIfNeeded: bits &>> 56)
            out &+= 1
            bits &<<= 8
            pending &-= 8
        }
        return (bits, pending, out, true)
    }

    /// Pads the last byte with ones (EOS's first bits) and stores it.
    @inline(__always)
    mutating func finish() -> Bool {
        guard flush() else { return false }
        if pending > 0 {
            guard out < capacity else { return false }
            // Unsafe: an unchecked store. Safe: out < capacity.
            unsafe base[out] = UInt8(truncatingIfNeeded: (bits | ~0 &>> pending) &>> 56)
            out &+= 1
            pending = 0
        }
        return true
    }
}

/// Four codes (entries: the code left-aligned in bits 32-63, its length in bits 0-7) merged with their lengths' prefix
/// sums, which don't depend on the writer, then added at once; over 56 bits (rare bytes), one at a time.
@inline(__always)
func addFour(_ e0: UInt64, _ e1: UInt64, _ e2: UInt64, _ e3: UInt64, _ writer: inout MSBWriter) -> Bool {
    let s1 = e0 & 0xFF
    let s2 = s1 &+ e1 & 0xFF
    let s3 = s2 &+ e2 & 0xFF
    let total = s3 &+ e3 & 0xFF
    if _fastPath(total <= 56) {
        // The mask clears the lengths, which only the first two entries leave in bits 0-7.
        writer.add(leftAligned: (e0 | e1 &>> s1 | e2 &>> s2 | e3 &>> s3) & ~0xFF, length: total)
        return writer.flush()
    }
    let ok: Bool
    (writer.bits, writer.pending, writer.out, ok) = unsafe addOneByOne(
        e0, e1, e2, e3, writer.bits, writer.pending, writer.out, writer.base, writer.capacity)
    return ok
}

/// Values in and out, so the caller's writer stays in registers.
@inline(never)
func addOneByOne(
    _ e0: UInt64, _ e1: UInt64, _ e2: UInt64, _ e3: UInt64,
    _ bits: UInt64, _ pending: UInt64, _ out: Int, _ base: UnsafeMutablePointer<UInt8>, _ capacity: Int
) -> (UInt64, UInt64, Int, Bool) {
    var writer = unsafe MSBWriter(base, capacity: capacity, at: out)
    writer.bits = bits
    writer.pending = pending
    for e in [e0, e1, e2, e3] {
        writer.add(leftAligned: e & ~0xFF, length: e & 0xFF)
        guard writer.flush() else { return (writer.bits, writer.pending, writer.out, false) }
    }
    return (writer.bits, writer.pending, writer.out, true)
}

/// Huffman-codes `inputCount` bytes: 8 merged per flush when their codes fit 56 bits, else 4 and 4; the last 1-7 bytes
/// as batches padded with entry 256 (no bits).
/// - Parameter limit: Give up (-3) once the output reaches this offset; `.max` for never.
/// - Returns: Bytes written past `offset`, -1 if the output is full, -3 at the limit.
@inline(__always)
func huffmanEncodeBody(
    input: UnsafePointer<UInt8>?, inputCount: Int,
    output: UnsafeMutablePointer<UInt8>, offset: Int, capacity: Int, limit: Int
) -> Int {
    let checksLimit = limit != .max
    return hpackHuffmanEncodeTable.withUnsafeBufferPointer { table in
        // Unsafe: unchecked reads below. Safe: indices are bytes or 256, and the table has 257 entries; input offsets are
        // below inputCount (and with inputCount 0 nothing is read).
        let entries = table.baseAddress!
        var writer = unsafe MSBWriter(output, capacity: capacity, at: offset)
        var i = 0
        if let input = unsafe input {
            while i &+ 8 <= inputCount {
                if checksLimit && writer.out >= limit { return -3 }
                let e0 = unsafe entries[Int(input[i])], e1 = unsafe entries[Int(input[i &+ 1])]
                let e2 = unsafe entries[Int(input[i &+ 2])], e3 = unsafe entries[Int(input[i &+ 3])]
                let e4 = unsafe entries[Int(input[i &+ 4])], e5 = unsafe entries[Int(input[i &+ 5])]
                let e6 = unsafe entries[Int(input[i &+ 6])], e7 = unsafe entries[Int(input[i &+ 7])]
                let s1 = e0 & 0xFF
                let s2 = s1 &+ e1 & 0xFF
                let s3 = s2 &+ e2 & 0xFF
                let s4 = s3 &+ e3 & 0xFF
                let s5 = s4 &+ e4 & 0xFF
                let s6 = s5 &+ e5 & 0xFF
                let s7 = s6 &+ e6 & 0xFF
                let total = s7 &+ e7 & 0xFF
                if total <= 56 {
                    let merged = e0 | e1 &>> s1 | e2 &>> s2 | e3 &>> s3 | e4 &>> s4 | e5 &>> s5 | e6 &>> s6 | e7 &>> s7
                    writer.add(leftAligned: merged & ~0xFF, length: total)
                    guard writer.flush() else { return -1 }
                } else {
                    guard addFour(e0, e1, e2, e3, &writer), addFour(e4, e5, e6, e7, &writer) else { return -1 }
                }
                i &+= 8
            }
            if i &+ 4 <= inputCount {
                if checksLimit && writer.out >= limit { return -3 }
                guard addFour(
                    unsafe entries[Int(input[i])], unsafe entries[Int(input[i &+ 1])],
                    unsafe entries[Int(input[i &+ 2])], unsafe entries[Int(input[i &+ 3])], &writer) else { return -1 }
                i &+= 4
            }
            let remaining = inputCount &- i
            if remaining > 0 {
                if checksLimit && writer.out >= limit { return -3 }
                guard addFour(
                    unsafe entries[Int(input[i])],
                    unsafe entries[remaining > 1 ? Int(input[i &+ 1]) : 256],
                    unsafe entries[remaining > 2 ? Int(input[i &+ 2]) : 256], 0, &writer) else { return -1 }
            }
        }
        guard writer.finish() else { return -1 }
        if writer.out > limit { return -3 }
        return writer.out &- offset
    }
}

/// A string literal's length prefix (RFC 7541 §5.1, RFC 9204 §4.1.2): `mask` (2^N − 1) the prefix, the H flag at
/// `mask + 1`, `flags` above it. Returns its length, or -1 if it doesn't fit.
@inline(__always)
func writeLengthPrefix(_ length: Int, huffman: Bool, _ output: UnsafeMutablePointer<UInt8>, _ capacity: Int, mask: Int, flags: UInt8) -> Int {
    guard capacity >= 1 else { return -1 }
    let flag: UInt8 = flags | (huffman ? UInt8(truncatingIfNeeded: mask &+ 1) : 0)
    if length < mask {
        // Unsafe: an unchecked store. Safe: capacity >= 1.
        unsafe output[0] = flag | UInt8(truncatingIfNeeded: length)
        return 1
    }
    // Unsafe: an unchecked store. Safe: capacity >= 1.
    unsafe output[0] = flag | UInt8(truncatingIfNeeded: mask)
    var value = length &- mask
    var n = 1
    while value >= 128 {
        guard n < capacity else { return -1 }
        // Unsafe: an unchecked store. Safe: n < capacity.
        unsafe output[n] = UInt8(truncatingIfNeeded: value) | 0x80
        value &>>= 7
        n &+= 1
    }
    guard n < capacity else { return -1 }
    // Unsafe: an unchecked store. Safe: n < capacity.
    unsafe output[n] = UInt8(truncatingIfNeeded: value)
    return n &+ 1
}

@inline(__always)
func prefixLength(_ length: Int, mask: Int) -> Int {
    if length < mask { return 1 }
    var value = length &- mask
    var n = 2
    while value >= 128 { value &>>= 7; n &+= 1 }
    return n
}

/// The string literal: optimistic Huffman after a one-byte prefix, else raw. Returns its length or -1.
@inline(__always)
func stringLiteral(
    _ input: UnsafePointer<UInt8>?, _ count: Int, _ output: UnsafeMutablePointer<UInt8>, _ capacity: Int, mask: Int, flags: UInt8
) -> Int {
    guard capacity >= 1 else { return -1 }
    // Huffman only if shorter: give up at `count` bytes of code (-3); full (-1) with room for the raw string means the
    // code wasn't shorter either. (A shorter code's prefix is never longer, so the whole literal is shorter too.)
    let n = unsafe huffmanEncodeBody(
        input: input, inputCount: count, output: output, offset: 1, capacity: capacity, limit: count &+ 1)
    if n < 0 || n >= count {
        let p = unsafe writeLengthPrefix(count, huffman: false, output, capacity, mask: mask, flags: flags)
        guard p > 0, p &+ count <= capacity else { return -1 }
        // Unsafe: copies count bytes into [p, p + count), checked against capacity just above.
        if count > 0 { unsafe (output + p).update(from: input!, count: count) }
        return p &+ count
    }
    if n < mask {
        // Unsafe: an unchecked store. Safe: capacity >= 1.
        unsafe output[0] = flags | UInt8(truncatingIfNeeded: mask &+ 1) | UInt8(truncatingIfNeeded: n)
        return 1 &+ n
    }
    let p = prefixLength(n, mask: mask)
    guard p &+ n <= capacity else { return -1 }
    // Unsafe: an overlapping move (memmove) within [1, p + n), checked against capacity just above.
    unsafe (output + p).update(from: output + 1, count: n)
    _ = unsafe writeLengthPrefix(n, huffman: true, output, p, mask: mask, flags: flags)
    return p &+ n
}

// MARK: - Entry points: out of line, called from inlinable code

/// Huffman-codes `inputCount` bytes into `output` (no length prefix).
/// - Returns: Bytes written, or -1 if the output is full.
@usableFromInline @inline(never)
package func huffmanEncode(
    _ input: UnsafePointer<UInt8>?, _ inputCount: Int, _ output: UnsafeMutablePointer<UInt8>, _ capacity: Int
) -> Int {
    unsafe huffmanEncodeBody(input: input, inputCount: inputCount, output: output, offset: 0, capacity: capacity, limit: .max)
}

/// Writes a string literal (RFC 7541 §5.2): length prefix with the H flag, then the Huffman code if it's shorter than
/// the bytes, else the bytes.
/// - Returns: Bytes written, or -1 if the output is full.
@usableFromInline @inline(never)
package func huffmanStringLiteral(
    _ input: UnsafePointer<UInt8>?, _ count: Int, _ output: UnsafeMutablePointer<UInt8>, _ capacity: Int
) -> Int {
    unsafe stringLiteral(input, count, output, capacity, mask: 0x7F, flags: 0)
}

/// Writes a string literal with a `prefixMask` (2^N − 1, N from 1 to 7) length prefix whose H flag is `prefixMask + 1`,
/// `flags` in the first byte's bits above it (QPACK's literal names have 3- and 5-bit prefixes, RFC 9204 §4.1.2), then
/// the Huffman code if it's shorter than the bytes, else the bytes.
/// - Returns: Bytes written, or -1 if the output is full.
@usableFromInline @inline(never)
package func huffmanStringLiteral(
    _ input: UnsafePointer<UInt8>?, _ count: Int, _ output: UnsafeMutablePointer<UInt8>, _ capacity: Int, prefixMask: Int, flags: UInt8
) -> Int {
    unsafe stringLiteral(input, count, output, capacity, mask: prefixMask, flags: flags)
}

/// The length of `count` bytes Huffman-coded, in bytes.
@usableFromInline
package func huffmanEncodedCount(_ input: UnsafePointer<UInt8>?, _ count: Int) -> Int {
    guard let input = unsafe input else { return 0 }
    var bits = 0
    for i in 0..<count {
        // Unsafe: an unchecked read. Safe: i < count, the input's length.
        bits &+= Int(truncatingIfNeeded: hpackHuffmanEncodeTable[Int(unsafe input[i])] & 0xFF)
    }
    return (bits &+ 7) &>> 3
}
