#!/usr/bin/perl
# Generates insn.c (to stdout): latency and throughput of single AArch64 instructions on one core, each
# measurement a loop entirely in inline asm. Tools/probe compiles the result with `-mcpu=apple-m1` (the floor
# ISA) into its cache; run it through `Tools/probe insn`, not by hand.
#
# Method (Tools/probes/README.md has the reasoning):
# - Latency: one dependent chain (every instruction reads the previous one's result).
# - Throughput: 8, 16, and 24 independent chains. A chain issues once per latency, so C chains can show at most
#   C / latency per cycle: 8 chains cap a 3-cycle instruction at 2.7. The probe reports the best of the three
#   and the 8-chain value (comparable with older 8-chain data).
# - Cycles come from a dependent scalar `add` chain (1 cycle each), timed before and after every sweep.
# - Templates write `D` for the chained register: v8..v31 for vector instructions, 24 general registers for
#   scalar ones. v1..v5 and x1 hold constant operands (tables are {v1-v4}). Every loop body has 48 templates,
#   a multiple of every chain count.
# - Instructions a chip may lack name their `hw.optional.arm.FEAT_*` sysctl; the program skips them (with a
#   note) when the sysctl isn't 1, and a SIGILL handler turns a wrong guess into a skipped row, never a crash.
use strict; use warnings;

# name, template, required feature (hw.optional.arm.FEAT_<name>; '' for base ARMv8.4/apple-m1), assembler
# directive needed above the floor ISA ('' if none).
my @insns = (
  ['add.16b',        'add vD.16b, vD.16b, v1.16b', '', ''],
  ['eor.16b',        'eor vD.16b, vD.16b, v1.16b', '', ''],
  ['eor3',           'eor3 vD.16b, vD.16b, v1.16b, v2.16b', 'SHA3', ''],
  ['bcax',           'bcax vD.16b, vD.16b, v1.16b, v2.16b', 'SHA3', ''],
  ['shl.4s',         'shl vD.4s, vD.4s, #1', '', ''],
  ['zip1.16b',       'zip1 vD.16b, vD.16b, v1.16b', '', ''],
  ['uzp1.16b',       'uzp1 vD.16b, vD.16b, v1.16b', '', ''],
  ['ext.16b',        'ext vD.16b, vD.16b, v1.16b, #3', '', ''],
  ['rev32.16b',      'rev32 vD.16b, vD.16b', '', ''],
  ['tbl 1 reg',      'tbl vD.16b, {v1.16b}, vD.16b', '', ''],
  ['tbl 2 regs',     'tbl vD.16b, {v1.16b, v2.16b}, vD.16b', '', ''],
  ['tbl 3 regs',     'tbl vD.16b, {v1.16b, v2.16b, v3.16b}, vD.16b', '', ''],
  ['tbl 4 regs',     'tbl vD.16b, {v1.16b, v2.16b, v3.16b, v4.16b}, vD.16b', '', ''],
  ['tbx 1 reg',      'tbx vD.16b, {v1.16b}, v5.16b', '', ''],
  ['tbx 2 regs',     'tbx vD.16b, {v1.16b, v2.16b}, v5.16b', '', ''],
  ['tbx 4 regs',     'tbx vD.16b, {v1.16b, v2.16b, v3.16b, v4.16b}, v5.16b', '', ''],
  ['tbx 2 regs via index', 'tbx vD.16b, {v1.16b, v2.16b}, vD.16b', '', ''],
  ['tbx 4 regs via index', 'tbx vD.16b, {v1.16b, v2.16b, v3.16b, v4.16b}, vD.16b', '', ''],
  ['usra.2d',        'usra vD.2d, v1.2d, #3', '', ''],
  ['mul.4s',         'mul vD.4s, vD.4s, v1.4s', '', ''],
  ['umull.8h',       'umull vD.8h, vD.8b, v1.8b', '', ''],
  ['udot.4s',        'udot vD.4s, v1.16b, v2.16b', 'DotProd', ''],
  ['pmull.1q',       'pmull vD.1q, vD.1d, v1.1d', 'PMULL', ''],
  ['pmull2.1q',      'pmull2 vD.1q, vD.2d, v1.2d', 'PMULL', ''],
  ['aese',           'aese vD.16b, v1.16b', 'AES', ''],
  ['aesmc',          'aesmc vD.16b, vD.16b', 'AES', ''],
  ['aese+aesmc pair','aese vD.16b, v1.16b' . '\n\t' . 'aesmc vD.16b, vD.16b', 'AES', ''],
  ['fmla.4s',        'fmla vD.4s, v1.4s, v2.4s', '', ''],
  ['sha256h',        'sha256h qD, q1, v2.4s', 'SHA256', ''],
  ['sha512h',        'sha512h qD, q1, v2.2d', 'SHA512', ''],
  ['ummla.4s',       'ummla vD.4s, v1.16b, v2.16b', 'I8MM', '.arch_extension i8mm'],
  ['bfdot.4s',       'bfdot vD.4s, v1.8h, v2.8h', 'BF16', '.arch_extension bf16'],
  ['crc32x (scalar)','crc32x wD, wD, x1', 'CRC32', ''],
  ['mul x (scalar)', 'mul xD, xD, x1', '', ''],
);
my @ways = (1, 8, 16, 24);
my $unroll = 48;                                  # a multiple of every chain count
my @vregs = (8 .. 31);                            # 24 vector chain registers
my @xregs = (2 .. 15, 19 .. 28);                  # 24 general registers (not x0, x1, x16-x18, x29, x30)

sub body {
  my ($tmpl, $ways, $regs) = @_;
  my @lines;
  for my $i (0 .. $unroll - 1) {
    my $reg = $regs->[$i % $ways];
    (my $l = $tmpl) =~ s/D/$reg/g;
    push @lines, $l;
  }
  return join('\n\t', @lines);
}
my $clobbers = join(', ', (map { "\"x$_\"" } 1 .. 17, 19 .. 28), (map { "\"v$_\"" } 0 .. 31), '"cc"');
my $init = join('\n\t',
  'movi v1.16b, #3', 'movi v2.16b, #5', 'movi v3.16b, #7', 'movi v4.16b, #9', 'movi v5.16b, #2', 'mov x1, #12345',
  (map { "movi v$_.16b, #1" } @vregs), (map { "mov x$_, #3" } @xregs));

print <<"C";
// Generated by Tools/probes/gen-insn.pl: don't edit, edit the generator.
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <unistd.h>
#include <signal.h>
#include <setjmp.h>
#include <time.h>
#include <pthread.h>
#include <sys/qos.h>
#include <sys/sysctl.h>
#define UNROLL $unroll
#define INIT "$init\\n\\t"
static inline uint64_t now(void) { return clock_gettime_nsec_np(CLOCK_UPTIME_RAW); }
C

my $cal = join('\n\t', ('add x2, x2, #1') x $unroll);
print "static double run_cal(long iters) { uint64_t t = now(); register long n __asm__(\"x0\") = iters; "
    . "__asm__ volatile(INIT \"1:\\n\\t$cal\\n\\tsubs x0, x0, #1\\n\\tb.ne 1b\" : \"+r\"(n) :: $clobbers); return (double)(now() - t); }\n";
my $n = 0;
my @rows;
for my $insn (@insns) {
  my ($name, $tmpl, $feature, $directive) = @$insn;
  my $regs = $tmpl =~ /^\w+ [wx]D/ ? \@xregs : \@vregs;
  my $pre = $directive ? "$directive\\n\\t" : '';
  my @fns;
  for my $ways (@ways) {
    my $b = body($tmpl, $ways, $regs);
    my $fn = "f$n"; $n++;
    print "static double $fn(long iters) { uint64_t t = now(); register long n __asm__(\"x0\") = iters; "
        . "__asm__ volatile(\"$pre\" INIT \"1:\\n\\t$b\\n\\tsubs x0, x0, #1\\n\\tb.ne 1b\" : \"+r\"(n) :: $clobbers); return (double)(now() - t); }\n";
    push @fns, $fn;
  }
  push @rows, "  {\"$name\", \"$feature\", {" . join(', ', @fns) . "}},\n";
}
my $nways = scalar @ways;
my $waylist = join(', ', @ways);
print "typedef double (*fn_t)(long);\n#define NWAYS $nways\nstatic const int ways[NWAYS] = {$waylist};\n";
print "struct probe { const char *name; const char *feature; fn_t fn[NWAYS]; };\nstatic struct probe probes[] = {\n", @rows, "};\n";
print <<'C';
#define NPROBES (int)(sizeof probes / sizeof probes[0])
#define MAXRUNS 15

static int has_feature(const char *feature) {
    if (!*feature) return 1;
    char key[128]; int value = 0; size_t size = sizeof value;
    snprintf(key, sizeof key, "hw.optional.arm.FEAT_%s", feature);
    return sysctlbyname(key, &value, &size, 0, 0) == 0 && value == 1;
}

static sigjmp_buf illegal;
static void on_sigill(int sig) { (void)sig; siglongjmp(illegal, 1); }

// Best (smallest) time of `reps` calls, or -1 if the instruction raised SIGILL.
static double best(fn_t f, long iters, int reps) {
    if (sigsetjmp(illegal, 1)) return -1;
    double b = 1e30;
    for (int i = 0; i < reps; i++) { double t = f(iters); if (t < b) b = t; }
    return b;
}
static double ghz_of(long iters, int reps) { return (double)iters * UNROLL / best(run_cal, iters, reps); }

static int compare_doubles(const void *a, const void *b) { double x = *(const double *)a, y = *(const double *)b; return (x > y) - (x < y); }
static double median(const double *values, int count) {
    double sorted[MAXRUNS]; memcpy(sorted, values, count * sizeof *values);
    qsort(sorted, count, sizeof *sorted, compare_doubles);
    return count % 2 ? sorted[count / 2] : (sorted[count / 2 - 1] + sorted[count / 2]) / 2;
}
static double spread_pct(const double *values, int count) {
    double lo = values[0], hi = values[0];
    for (int i = 1; i < count; i++) { if (values[i] < lo) lo = values[i]; if (values[i] > hi) hi = values[i]; }
    double m = median(values, count);
    return m > 0 ? (hi - lo) / m * 100 : 0;
}

static void usage(void) {
    fprintf(stderr, "usage: insn [-r RUNS] [-n REPS] [-i ITERS] [-w WARMUP_MS] [-c CLOCK_TSV] [-o NAME] [-l]\n"
                    "  -r runs (sweeps over every instruction; medians are reported), -n best of N per measurement,\n"
                    "  -i loop iterations (each %d instructions), -w warm-up time, -c write the clock table there,\n"
                    "  -o only instructions whose name contains NAME, -l list the instructions and their required features\n", UNROLL);
    exit(2);
}

int main(int argc, char **argv) {
    int runs = 3, reps = 3, warmup_ms = 400, opt;
    long iters = 16000000 / UNROLL;  // 16 M instructions per measurement
    const char *clock_path = 0, *only = 0;
    while ((opt = getopt(argc, argv, "r:n:i:w:c:o:l")) != -1) {
        switch (opt) {
            case 'r': runs = atoi(optarg); break;
            case 'n': reps = atoi(optarg); break;
            case 'i': iters = atol(optarg); break;
            case 'w': warmup_ms = atoi(optarg); break;
            case 'c': clock_path = optarg; break;
            case 'o': only = optarg; break;
            case 'l': for (int i = 0; i < NPROBES; i++) printf("%s\t%s\n", probes[i].name, *probes[i].feature ? probes[i].feature : "-"); return 0;
            default: usage();
        }
    }
    if (runs < 1 || runs > MAXRUNS || reps < 1 || iters < 1) usage();
    pthread_set_qos_class_self_np(QOS_CLASS_USER_INTERACTIVE, 0);
    struct sigaction action = {0};
    action.sa_handler = on_sigill;
    sigaction(SIGILL, &action, 0);

    int supported[NPROBES];
    int shown[NPROBES];
    for (int i = 0; i < NPROBES; i++) {
        supported[i] = has_feature(probes[i].feature);
        shown[i] = !only || strstr(probes[i].name, only) != 0;
        if (shown[i] && !supported[i]) fprintf(stderr, "note: skipping %s: hw.optional.arm.FEAT_%s isn't 1 on this Mac\n", probes[i].name, probes[i].feature);
    }
    static double ns[NPROBES][NWAYS][MAXRUNS];
    static double ghz[NPROBES][MAXRUNS];
    double before[MAXRUNS], after[MAXRUNS];

    // Warm up: keep the core busy until its clock has ramped (the first calibration otherwise reads low).
    uint64_t until = now() + (uint64_t)warmup_ms * 1000000;
    while (now() < until) run_cal(iters / 4);

    for (int run = 0; run < runs; run++) {
        before[run] = ghz_of(iters, 7);
        for (int i = 0; i < NPROBES; i++) {
            if (!supported[i] || !shown[i]) continue;
            // Calibrate next to each instruction: the clock can move during a run (other cores waking change
            // the cluster's frequency), and one calibration per run would misprice the rows measured after a change.
            ghz[i][run] = ghz_of(iters / 4, 3);
            for (int w = 0; w < NWAYS; w++) {
                double t = best(probes[i].fn[w], iters, reps);
                if (t < 0) {
                    fprintf(stderr, "note: %s raised SIGILL (the sysctl said FEAT_%s); skipped\n", probes[i].name, probes[i].feature);
                    supported[i] = 0; break;
                }
                ns[i][w][run] = t;
            }
        }
        after[run] = ghz_of(iters, 7);
    }

    if (clock_path) {
        FILE *f = fopen(clock_path, "w");
        if (!f) { perror(clock_path); return 1; }
        fprintf(f, "run\tbefore_GHz\tafter_GHz\n");
        for (int run = 0; run < runs; run++) fprintf(f, "%d\t%.3f\t%.3f\n", run + 1, before[run], after[run]);
        fprintf(f, "median\t%.3f\t%.3f\n", median(before, runs), median(after, runs));
        fclose(f);
    }
    double med_clock = (median(before, runs) + median(after, runs)) / 2;
    fprintf(stderr, "clock: %.3f GHz before, %.3f after (medians of %d runs)\n", median(before, runs), median(after, runs), runs);
    for (int run = 0; run < runs; run++)
        if (before[run] < med_clock * 0.95 || after[run] < med_clock * 0.95)
            fprintf(stderr, "warning: run %d's clock read %.3f/%.3f GHz, more than 5%% below the median: the core was shared or slowed\n", run + 1, before[run], after[run]);

    printf("instruction\tlatency_cycles\tper_cycle\tbest_chains");
    for (int w = 1; w < NWAYS; w++) printf("\tper_cycle_%dchains", ways[w]);
    printf("\tlatency_spread_pct\tper_cycle_spread_pct\n");
    for (int i = 0; i < NPROBES; i++) {
        if (!shown[i]) continue;
        if (!supported[i]) {
            printf("%s\t-\t-\t-", probes[i].name);
            for (int w = 1; w < NWAYS; w++) printf("\t-");
            printf("\t-\t-\n");
            continue;
        }
        double cycles[NWAYS][MAXRUNS], rate[NWAYS][MAXRUNS], med[NWAYS];
        for (int w = 0; w < NWAYS; w++) {
            for (int run = 0; run < runs; run++) {
                cycles[w][run] = ns[i][w][run] / ((double)iters * UNROLL) * ghz[i][run];  // per template (a pair counts once)
                rate[w][run] = 1 / cycles[w][run];
            }
            med[w] = median(rate[w], runs);
        }
        // per_cycle is the best chain count's median; best_chains the fewest chains within 3% of it (where the
        // rate stops growing: about latency x issue width).
        int maxw = 1, fewest = 1;
        for (int w = 2; w < NWAYS; w++) if (med[w] > med[maxw]) maxw = w;
        while (med[fewest] < med[maxw] * 0.97) fewest++;
        printf("%s\t%.2f\t%.2f\t%d", probes[i].name, median(cycles[0], runs), med[maxw], ways[fewest]);
        for (int w = 1; w < NWAYS; w++) printf("\t%.2f", med[w]);
        printf("\t%.1f\t%.1f\n", spread_pct(cycles[0], runs), spread_pct(rate[maxw], runs));
    }
    return 0;
}
